CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA extensions;

-- 1. User profiles
CREATE TABLE public.profiles (
    id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    display_name text NOT NULL DEFAULT '',
    job_title text NOT NULL DEFAULT '',
    last_catchup_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.profiles (id, display_name)
    VALUES (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'display_name', '')
    )
    ON CONFLICT (id) DO NOTHING;
    RETURN new;
END;
$$;

CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- 2. Projects
CREATE TABLE public.projects (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL DEFAULT auth.uid()
        REFERENCES auth.users(id) ON DELETE CASCADE,
    name text NOT NULL,
    symbol text NOT NULL DEFAULT 'P',
    summary text NOT NULL DEFAULT '',
    deadline date,
    progress smallint NOT NULL DEFAULT 0
        CHECK (progress BETWEEN 0 AND 100),
    risk text NOT NULL DEFAULT '',
    color text NOT NULL DEFAULT '#4263eb',
    soft_color text NOT NULL DEFAULT '#eef2ff',
    members text[] NOT NULL DEFAULT '{}',
    origin text NOT NULL DEFAULT 'user'
        CHECK (origin IN ('user', 'ai')),
    category text NOT NULL DEFAULT 'project'
        CHECK (category IN (
            'project', 'meeting_series', 'training',
            'conference', 'interview', 'admin'
        )),
    catchup_summary text,
    catchup_summary_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Connected accounts
CREATE TABLE public.source_connections (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL DEFAULT auth.uid()
        REFERENCES auth.users(id) ON DELETE CASCADE,
    provider text NOT NULL
        CHECK (provider IN ('gmail', 'google_calendar')),
    provider_account_id text NOT NULL,
    account_email text NOT NULL,
    status text NOT NULL DEFAULT 'active'
        CHECK (status IN (
            'active', 'expired', 'error', 'disconnected'
        )),
    sync_cursor text,
    last_synced_at timestamptz,
    last_error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, provider, provider_account_id)
);

-- 4. Imported source information
CREATE TABLE public.source_items (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id uuid NOT NULL DEFAULT auth.uid()
        REFERENCES auth.users(id) ON DELETE CASCADE,
    connection_id uuid
        REFERENCES public.source_connections(id) ON DELETE CASCADE,
    source_type text NOT NULL
        CHECK (source_type IN ('upload', 'gmail', 'google_calendar')),
    external_id text,
    external_thread_id text,
    title text NOT NULL DEFAULT '',
    text_excerpt text NOT NULL DEFAULT ''
        CHECK (char_length(text_excerpt) <= 2000),
    extracted_text text,
    sender text,
    participants text[] NOT NULL DEFAULT '{}',
    mime_type text,
    file_name text,
    storage_path text,
    source_url text,
    occurred_at timestamptz,
    ends_at timestamptz,
    location text,
    processing_status text NOT NULL DEFAULT 'pending'
        CHECK (processing_status IN (
            'pending', 'processing', 'processed', 'failed'
        )),
    processing_error text,
    normalized_at timestamptz,
    content_hash text,
    include_in_grouping boolean NOT NULL DEFAULT true,
    exclusion_reason text,
    deduped_at timestamptz,
    embedding extensions.vector(384),
    embedded_at timestamptz,
    extracted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (
        (
            source_type IN ('gmail', 'google_calendar')
            AND connection_id IS NOT NULL
            AND external_id IS NOT NULL
        ) OR source_type = 'upload'
    ),
    UNIQUE (connection_id, external_id)
);

-- 5. Links between projects and sources
CREATE TABLE public.project_source_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL DEFAULT auth.uid()
        REFERENCES auth.users(id) ON DELETE CASCADE,
    project_id uuid NOT NULL
        REFERENCES public.projects(id) ON DELETE CASCADE,
    source_item_id uuid NOT NULL
        REFERENCES public.source_items(id) ON DELETE CASCADE,
    match_method text NOT NULL DEFAULT 'ai'
        CHECK (match_method IN ('manual', 'rule', 'ai')),
    confidence numeric(5,4) CHECK (confidence BETWEEN 0 AND 1),
    explanation text,
    review_status text NOT NULL DEFAULT 'pending'
        CHECK (review_status IN ('pending', 'confirmed', 'rejected')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, source_item_id)
);

-- 6. Timeline events
CREATE TABLE public.project_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL DEFAULT auth.uid()
        REFERENCES auth.users(id) ON DELETE CASCADE,
    project_id uuid NOT NULL
        REFERENCES public.projects(id) ON DELETE CASCADE,
    source_item_id uuid
        REFERENCES public.source_items(id) ON DELETE SET NULL,
    event_type text NOT NULL
        CHECK (event_type IN (
            'email', 'file', 'meeting', 'decision',
            'deadline', 'status', 'note', 'issue'
        )),
    title text NOT NULL,
    body text NOT NULL DEFAULT '',
    person text NOT NULL DEFAULT '',
    event_date timestamptz NOT NULL DEFAULT now(),
    requires_response boolean,
    confidence numeric(5,4) CHECK (confidence BETWEEN 0 AND 1),
    user_edited boolean NOT NULL DEFAULT false,
    color text NOT NULL DEFAULT '#4263eb',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- 7. Project action items
CREATE TABLE public.project_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL DEFAULT auth.uid()
        REFERENCES auth.users(id) ON DELETE CASCADE,
    project_id uuid NOT NULL
        REFERENCES public.projects(id) ON DELETE CASCADE,
    source_item_id uuid
        REFERENCES public.source_items(id) ON DELETE SET NULL,
    title text NOT NULL,
    assignee text,
    due_date date,
    completed boolean NOT NULL DEFAULT false,
    status text NOT NULL DEFAULT 'not_started'
        CHECK (status IN (
            'not_started', 'in_progress', 'completed'
        )),
    backlog boolean NOT NULL DEFAULT false,
    confidence numeric(5,4) CHECK (confidence BETWEEN 0 AND 1),
    user_edited boolean NOT NULL DEFAULT false,
    color text NOT NULL DEFAULT '#4263eb',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- 8. User corrections and confirmations
CREATE TABLE public.user_corrections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL DEFAULT auth.uid()
        REFERENCES auth.users(id) ON DELETE CASCADE,
    source_item_id uuid
        REFERENCES public.source_items(id) ON DELETE SET NULL,
    project_id uuid
        REFERENCES public.projects(id) ON DELETE SET NULL,
    correction_type text NOT NULL
        CHECK (correction_type IN (
            'confirm_match', 'reject_match', 'move_project',
            'edit_event', 'edit_action', 'edit_project'
        )),
    previous_value jsonb,
    corrected_value jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- 9. Semantic item relationships
CREATE TABLE public.item_relationships (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL DEFAULT auth.uid()
        REFERENCES auth.users(id) ON DELETE CASCADE,
    source_item_id uuid NOT NULL
        REFERENCES public.source_items(id) ON DELETE CASCADE,
    related_item_id uuid NOT NULL
        REFERENCES public.source_items(id) ON DELETE CASCADE,
    semantic_score numeric(6,5)
        CHECK (semantic_score BETWEEN -1 AND 1),
    deterministic_score numeric(6,5)
        CHECK (deterministic_score BETWEEN 0 AND 1),
    combined_score numeric(6,5)
        CHECK (combined_score BETWEEN 0 AND 1),
    signals jsonb NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (source_item_id, related_item_id)
);

-- 10. Backend-only encrypted OAuth tokens
CREATE TABLE public.source_secrets (
    connection_id uuid PRIMARY KEY
        REFERENCES public.source_connections(id) ON DELETE CASCADE,
    user_id uuid NOT NULL
        REFERENCES auth.users(id) ON DELETE CASCADE,
    encrypted_token text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Indexes for retrieval and processing
CREATE INDEX projects_user_id_idx ON public.projects(user_id);
CREATE INDEX projects_user_origin_idx ON public.projects(user_id, origin);
CREATE INDEX source_connections_user_id_idx
    ON public.source_connections(user_id);
CREATE INDEX source_items_user_status_idx
    ON public.source_items(user_id, processing_status);
CREATE INDEX source_items_occurred_at_idx
    ON public.source_items(user_id, occurred_at DESC);
CREATE INDEX source_items_normalize_queue_idx
    ON public.source_items(user_id)
    WHERE processing_status = 'pending' AND normalized_at IS NULL;
CREATE INDEX source_items_dedupe_queue_idx
    ON public.source_items(user_id)
    WHERE processing_status = 'pending'
      AND normalized_at IS NOT NULL AND deduped_at IS NULL;
CREATE INDEX source_items_grouping_ready_idx
    ON public.source_items(user_id)
    WHERE deduped_at IS NOT NULL AND include_in_grouping;
CREATE INDEX source_items_extract_queue_idx
    ON public.source_items(user_id)
    WHERE extracted_at IS NULL;
CREATE INDEX source_items_embedding_idx
    ON public.source_items
    USING hnsw (embedding extensions.vector_cosine_ops);
CREATE INDEX project_source_links_project_id_idx
    ON public.project_source_links(project_id);
CREATE INDEX project_source_links_source_item_id_idx
    ON public.project_source_links(source_item_id);
CREATE INDEX project_events_project_date_idx
    ON public.project_events(project_id, event_date DESC);
CREATE INDEX project_actions_project_due_idx
    ON public.project_actions(project_id, due_date);
CREATE INDEX user_corrections_user_id_idx
    ON public.user_corrections(user_id);
CREATE INDEX item_relationships_user_id_idx
    ON public.item_relationships(user_id);
CREATE INDEX item_relationships_source_idx
    ON public.item_relationships(source_item_id);
CREATE INDEX item_relationships_combined_idx
    ON public.item_relationships(user_id, combined_score DESC);
CREATE INDEX source_secrets_user_id_idx
    ON public.source_secrets(user_id);

